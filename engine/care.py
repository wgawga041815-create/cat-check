def home_care(level, triage):
    base = []
    if level == "emergency":
        base = [
            "先去医院，家庭护理只在路上进行：保暖、安静、航空箱固定。",
            "不要喂食、喂水、喂药，除非医生电话指导。",
            "拍下呕吐物/粪便/尿液照片，带上误食物包装。",
        ]
    elif level == "urgent":
        base = [
            "记录 24 小时出入量：吃了多少克、喝多少水、几个尿团、几次呕吐/排便。",
            "把猫隔离到安静房间，保证它能随时喝到水、走到猫砂盆。",
            "不要自行加药、换粮、洗澡；就诊前禁食 4–6 小时（除非糖尿病或幼猫）。",
            "体温：肛温 38.0–39.2℃ 为正常，家里没有兽用体温计就不要强测。",
        ]
    elif level == "monitor":
        base = [
            "做一个 3 天观察表：食欲、饮水、尿团数、精神状态、体重。",
            "维持原有饮食与猫砂，不要同时换粮换砂——变量太多就看不出因果。",
            "增加饮水点、减少应激源（噪音、新宠物、搬家）。",
        ]
    else:
        base = [
            "每周固定时间称重，记录曲线，比“看着不胖”可靠。",
            "每天铲屎时看一眼尿团：数量、大小、颜色是最便宜的体检。",
            "每月摸一遍全身（下颌、腋下、腹股沟、乳腺），记录任何新肿块。",
        ]
    if triage.get("red_flags"):
        base.insert(0, "已经出现急症信号，以下护理不能替代就医。")
    return base


